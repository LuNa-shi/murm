#!/usr/bin/env node
// Offline inventory check. This detects source/reference drift, not semantic completeness.
import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, relative, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/generate-architecture-coverage.mjs [--check]');
const map = JSON.parse(await readFile(resolve(root, 'docs/architecture/source-map.json'), 'utf8'));
if (map.schema_version !== 1 || !Array.isArray(map.files)) throw new Error('Unsupported architecture source map');
const safe = (path) => typeof path === 'string' && path !== '' && !path.startsWith('/') && !path.startsWith('../') && posix.normalize(path) === path && !path.includes('\\');
// Git worktrees and local agent metadata are workspace state, not repository
// runtime inputs. They can contain dependency symlinks and must never affect
// the tracked source inventory.
const skipRoots = new Set(['.git', '.worktree', '.worktrees', '.claude', 'node_modules', '.codex', 'docs', 'test', 'test-support', 'experiments', 'reports']);
async function walk(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (prefix === '' && skipRoots.has(entry.name)) continue;
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) throw new Error(`Source inventory needs an explicit symlink policy: ${path}`);
    if (entry.isDirectory()) files.push(...await walk(resolve(directory, entry.name), path));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}
const discovered = (await walk(root)).filter((path) =>
  map.scope_roots.some((dir) => path.startsWith(`${dir}/`)) || map.scope_root_files.includes(path) ||
  /\.(?:[cm]?js|jsx|[cm]?ts|tsx|py|sh|json)$/.test(path) || posix.basename(path) === 'Dockerfile'
).sort();
const entries = [...map.files].sort((a, b) => a.path.localeCompare(b.path, 'en'));
const declared = new Set();
const failures = [];
for (const item of entries) {
  if (!safe(item.path) || declared.has(item.path)) throw new Error(`Invalid or duplicate source path: ${item.path}`);
  declared.add(item.path);
  if (!item.role || !item.category || !Array.isArray(item.chapters) || !item.chapters.length) failures.push(`Incomplete source mapping: ${item.path}`);
  if (!discovered.includes(item.path)) failures.push(`Mapped source missing or outside declared scope: ${item.path}`);
  for (const chapter of item.chapters ?? []) {
    if (!safe(chapter) || !chapter.startsWith('docs/architecture/') || !chapter.endsWith('.md')) throw new Error(`Invalid chapter path: ${chapter}`);
    // The coverage reference is the output of this very command on first generation.
    if (chapter === 'docs/architecture/12-code-coverage.md' && !check) continue;
    if (!await stat(resolve(root, chapter)).then((s) => s.isFile()).catch(() => false)) failures.push(`Missing chapter: ${chapter} (from ${item.path})`);
  }
}
for (const path of discovered) if (!declared.has(path)) failures.push(`Unmapped source: ${path}`);
if (failures.length) throw new Error(failures.join('\n'));

const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
let result = '# 12. Source coverage and reviewed fingerprints\n\n';
result += '> Generated by `node scripts/generate-architecture-coverage.mjs`. Check without writing with `--check`. Source ownership and purpose are maintained explicitly in [source-map.json](source-map.json).\n\n';
result += `Runtime baseline: \`${map.runtime_baseline}\`; review date: ${map.reviewed_date}. Runtime, configuration and documentation-tooling files are fingerprinted from the current tree. The baseline identifies the runtime tree used for this integration review; documentation-tooling fingerprints also include changes in the reviewed documentation branch. This is not a claim that every runtime branch was executed or semantically verified.\n\n`;
result += `The declared inventory contains **${entries.length} files**. Every in-scope file must have a role and an existing architecture chapter. New source files are rejected until deliberately mapped; removed files require mapping updates. Generated served assets and controlled fixtures are labeled separately below.\n\n`;
result += 'This is file-level coverage, not a claim of 100% branch verification. A matching hash says the referenced bytes are unchanged. It does not prove that prose is correct, tests passed, a provider launched, or collaboration succeeded. Maintain the narrative and review the whole affected flow before accepting regenerated fingerprints.\n\n';
result += '## Scope and explicit boundaries\n\n';
result += `In-scope roots: ${map.scope_roots.map((dir) => `\`${dir}/\``).join(', ')}. Root files: ${map.scope_root_files.map((path) => `\`${path}\``).join(', ')}. Additional code/JSON files discovered outside excluded roots also fail the check until mapped.\n\n`;
result += '| Outside production coverage | Reason |\n|---|---|\n';
for (const item of map.excluded) result += `| ${item.path} | ${item.reason} |\n`;
result += '\n## File-by-file ownership\n';
const groups = [...new Set(entries.map((item) => item.category))].sort();
for (const group of groups) {
  const rows = entries.filter((item) => item.category === group);
  result += `\n### ${group} (${rows.length})\n\n| Source | Responsibility | Architecture chapters | SHA-256 |\n|---|---|---|---|\n`;
  for (const item of rows) {
    const chapters = item.chapters.map((path) => `[${posix.basename(path, '.md')}](${relative(resolve(root, 'docs/architecture'), resolve(root, path)).split('\\').join('/')})`).join(', ');
    result += `| [${item.path}](../../${item.path}) | ${item.role} | ${chapters} | \`${sha(await readFile(resolve(root, item.path)))}\` |\n`;
  }
}
const destination = resolve(root, 'docs/architecture/12-code-coverage.md');
if (check) {
  const existing = await readFile(destination, 'utf8').catch(() => null);
  if (existing !== result) {
    console.error('Stale source coverage/fingerprints: docs/architecture/12-code-coverage.md');
    process.exitCode = 1;
  } else console.log(`Checked explicit architecture ownership and fingerprints for ${entries.length} files.`);
} else {
  await writeFile(destination, result);
  console.log(`Generated explicit architecture ownership and fingerprints for ${entries.length} files.`);
}
